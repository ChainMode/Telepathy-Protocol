test("negotiateProtocolContract selects tier_1_native_tp when ontologies match", () => {
  const res = negotiateProtocolContract(
    {
      fay_id: ALICE_FAY_ID,
      tp_version: "1.0",
      crypto_suites: ["Ed25519", "ML-DSA-65"],
      transports: [{ protocol: "dtp_tunnel", tunnel_id: "dtp_01" }, { protocol: "native_tp" }],
      supported_ontologies: [TRAVEL_ONTOLOGY_V1],
      security_level: "high"
    },
    {
      fay_id: BOB_FAY_ID,
      tp_version: "TP/1.0",
      crypto_suites: ["Ed25519"],
      transports: [{ protocol: "dtp_tunnel", tunnel_id: "dtp_01" }],
      supported_ontologies: [TRAVEL_ONTOLOGY_V1],
      security_level: "standard"
    },
    { now: "2026-11-16T00:00:00Z" }
  );

  assert.equal(res.ok, true);
  assert.equal(res.contract.communication_tier, "tier_1_native_tp");
  assert.equal(res.contract.fallback_active, false);
  assert.equal(res.contract.crypto_suite, "Ed25519");
  assert.equal(res.contract.transport_method.protocol, "dtp_tunnel");
  assert.equal(res.contract.shared_ontology.ontology_id, TRAVEL_ONTOLOGY_V1.ontology_id);
});

