test("validateCognitiveFrameExchange enforces 3-layer Normative Core and rejects heterogeneous raw latent frames", () => {
  const negotiated = negotiateProtocolContract(
    {
      fay_id: ALICE_FAY_ID,
      tp_version: "1.0",
      crypto_suites: ["Ed25519"],
      transports: [{ protocol: "native_tp" }],
      supported_ontologies: [TRAVEL_ONTOLOGY_V1],
      experimental_model_attestation: MODEL_ATTESTATION_A,
      allowExperimentalLatent: true
    },
    {
      fay_id: BOB_FAY_ID,
      tp_version: "1.0",
      crypto_suites: ["Ed25519"],
      transports: [{ protocol: "native_tp" }],
      supported_ontologies: [TRAVEL_ONTOLOGY_V1],
      experimental_model_attestation: MODEL_ATTESTATION_A,
      allowExperimentalLatent: true
    }
  );
  assert.equal(negotiated.ok, true);
  assert.equal(negotiated.contract.experimental_latent_enabled, true);

  // 1. Valid explicit cognitive frame
  const validCognitive = validateCognitiveFrameExchange(
    {
      frame_type: "explicit_cognitive_frame",
      frame_id: "cf_001",
      ontology_id: TRAVEL_ONTOLOGY_V1.ontology_id,
      ontology_version: "1.0",
      intent_summary: "Plan 3-day Kyoto rail itinerary",
      confidence: 0.92,
      assumptions: ["high-speed rail preferred"],
      constraints: ["budget <= 5000 CNY"],
      entities: { destination: "Kyoto", days: 3 },
      context_refs: ["ctx_01"]
    },
    negotiated.contract
  );
  assert.equal(validCognitive.ok, true);

  // 2. Low-confidence explicit cognitive frame triggers mandatory fallback requirement
  const lowConf = validateCognitiveFrameExchange(
    {
      frame_type: "explicit_cognitive_frame",
      frame_id: "cf_002",
      ontology_id: TRAVEL_ONTOLOGY_V1.ontology_id,
      ontology_version: "1.0",
      intent_summary: "Ambiguous destination",
      confidence: 0.35,
      assumptions: [],
      constraints: [],
      entities: {},
      context_refs: []
    },
    negotiated.contract,
    { minConfidence: 0.6 }
  );
  assert.equal(lowConf.ok, false);
  assert.equal(lowConf.requiresFallback, true);
  assert.equal(lowConf.error.error_code, "TP-COG002");

  // 3. Valid structured text fallback frame is always accepted
  const fallbackFrame = {
    frame_type: "structured_text_fallback",
    frame_id: "fb_001",
    fallback_reason: "ontology_mismatch",
    language: "zh-CN",
    intent_summary: "规划京都三日铁路行程",
    structured_sections: {
      intent: "生成京都三日无障碍文化行程草案",
      context: "参与方无共同旅游本体，启用结构化自然语言回退信道",
      constraints: ["预算不超过 5000 元", "优先轨道交通"],
      expected_outcome: "按日划分的结构化行程列表"
    },
    auditable_text: "[TP/1.0 Fallback] 意图：生成京都三日无障碍文化行程草案；约束：预算<=5000元，优先轨道交通。"
  };
  assert.equal(validateCognitiveFrameExchange(fallbackFrame, negotiated.contract).ok, true);

  // 4. Heterogeneous model raw latent frame MUST be rejected with TP-LAT002 (Scientific Honesty Redline!)
  const heterogeneousLatent = validateCognitiveFrameExchange(
    {
      frame_type: "experimental_latent_frame",
      experimental: true,
      frame_id: "lat_bad_01",
      sender_model_attestation: MODEL_ATTESTATION_A,
      receiver_model_attestation: MODEL_ATTESTATION_HETEROGENEOUS,
      vector_encoding: "float16_base64",
      vector_payload_b64: "AAECAwQFBgc=",
      audit_summary: "Attempted cross-model latent transfer",
      fallback_frame: fallbackFrame
    },
    negotiated.contract
  );
  assert.equal(heterogeneousLatent.ok, false);
  assert.equal(heterogeneousLatent.error.error_code, "TP-LAT002");

  // 5. Homogeneous model raw latent frame WITHOUT audit_summary MUST be rejected with TP-LAT003
  const opaqueLatent = validateCognitiveFrameExchange(
    {
      frame_type: "experimental_latent_frame",
      experimental: true,
      frame_id: "lat_bad_02",
      sender_model_attestation: MODEL_ATTESTATION_A,
      receiver_model_attestation: MODEL_ATTESTATION_A,
      vector_encoding: "float16_base64",
      vector_payload_b64: "AAECAwQFBgc=",
      audit_summary: "",
      fallback_frame: fallbackFrame
    },
    negotiated.contract
  );
  assert.equal(opaqueLatent.ok, false);
  assert.equal(opaqueLatent.error.error_code, "TP-LAT003");

  // 6. Homogeneous model raw latent frame WITH identical digests + audit_summary + fallback_frame succeeds
  const validHomogeneousLatent = validateCognitiveFrameExchange(
    {
      frame_type: "experimental_latent_frame",
      experimental: true,
      frame_id: "lat_ok_01",
      sender_model_attestation: MODEL_ATTESTATION_A,
      receiver_model_attestation: MODEL_ATTESTATION_A,
      vector_encoding: "float16_base64",
      vector_payload_b64: "AAECAwQFBgc=",
      audit_summary: "Homogeneous fay-ego-7b-v1 compressed itinerary preference vector (Kyoto, 3 days).",
      fallback_frame: fallbackFrame
    },
    negotiated.contract
  );
  assert.equal(validHomogeneousLatent.ok, true);
});

test("SessionStateMachine enforces strict 5-step ordering, halts on error, and supports Step 4 resumption", () => {
  const alice = makeAliceIdentity();
  const bob = makeBobIdentity();
  const sm = new SessionStateMachine({ timeoutMs: 30000, startTimeMs: 1000 });

  // Out-of-order Step 3 before Step 1 must fail with TP-SES001
  const outOfOrder = sm.exchangeProfiles(makeProfile(alice), makeProfile(bob));
  assert.equal(outOfOrder.ok, false);
  assert.equal(outOfOrder.error.error_code, "TP-SES001");
  assert.equal(sm.state, "halted");

  // Fresh 5-step session establishment
  const sm2 = new SessionStateMachine({ timeoutMs: 30000, startTimeMs: 1000 });
  const step1 = sm2.completeNegotiation(
    {
      fay_id: alice.fay_id,
      tp_version: "1.0",
      crypto_suites: ["Ed25519"],
      transports: [{ protocol: "native_tp" }],
      supported_ontologies: [TRAVEL_ONTOLOGY_V1]
    },
    {
      fay_id: bob.fay_id,
      tp_version: "1.0",
      crypto_suites: ["Ed25519"],
      transports: [{ protocol: "native_tp" }],
      supported_ontologies: [TRAVEL_ONTOLOGY_V1]
    },
    1500,
    { now: "2026-11-16T00:00:00Z" }
  );
  assert.equal(step1.ok, true);
  assert.equal(sm2.step, 1);

  const step2 = sm2.verifyIdentities(alice, bob, 2000);
  assert.equal(step2.ok, true);
  assert.equal(sm2.step, 2);

  const step3 = sm2.exchangeProfiles(
    makeProfile(alice, [TRAVEL_ONTOLOGY_V1]),
    makeProfile(bob, [TRAVEL_ONTOLOGY_V1]),
    2500
  );
  assert.equal(step3.ok, true);
  assert.equal(sm2.step, 3);

  const step4 = sm2.establishInitialContext({ context_id: "ctx_initial_01", state: "active" }, 3000);
  assert.equal(step4.ok, true);
  assert.equal(sm2.step, 4);

  const step5 = sm2.markReady(3500);
  assert.equal(step5.ok, true);
  assert.equal(sm2.step, 5);
  assert.equal(sm2.state, "ready");

  // Session resumption from cached valid contract starts directly at Step 3->4 boundary
  const resumed = SessionStateMachine.resumeFromCachedContract({
    contract: step1.contract,
    initiatorIdentity: alice,
    responderIdentity: bob,
    initiatorProfile: makeProfile(alice, [TRAVEL_ONTOLOGY_V1]),
    responderProfile: makeProfile(bob, [TRAVEL_ONTOLOGY_V1]),
    nowIso: "2026-11-16T00:05:00Z"
  });
  assert.equal(resumed.ok, true);
  assert.equal(resumed.session.step, 3);
  assert.equal(resumed.session.establishInitialContext({ context_id: "ctx_resumed_02", state: "active" }).ok, true);
  assert.equal(resumed.session.markReady().ok, true);
});
